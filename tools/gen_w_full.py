def _fmt(v):
    return ("%g" % float(v))


def build():
    rows = []
    dropped = []
    seen = set()
    for m, pairs in TABLES.items():
        for dB, z in pairs:
            if dB > MAX_DB:
                continue
            pitch = m * z
            tip = pitch + 0.9 * m
            if tip > dB + 1e-6:           # reference dia must reach the tip
                dropped.append((dB, m, z, round(tip, 3)))
                continue
            key = (dB, m, z)
            if key in seen:
                continue
            seen.add(key)
            root = pitch - 1.2 * m
            base = pitch * math.cos(math.radians(30.0))
            desig = "W%s\u00d7%s\u00d7%d" % (_fmt(dB), _fmt(m), z)
            rows.append({
                "desig": desig,
                "dB": _fmt(dB),
                "m": _fmt(m),
                "z": str(z),
                "pitch": _fmt(round(pitch, 3)),
                "tip": _fmt(round(tip, 3)),
                "root": _fmt(round(root, 3)),
                "base": _fmt(round(base, 3)),
            })
    rows.sort(key=lambda r: (float(r["dB"]), float(r["m"]), int(r["z"])))
    return rows, dropped


def main():
    rows, dropped = build()
    with open(OUT, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(
            fh, fieldnames=["desig", "dB", "m", "z", "pitch", "tip", "root", "base"]
        )
        w.writeheader()
        w.writerows(rows)
    print("wrote", OUT, len(rows), "rows")
    if dropped:
        print("dropped %d geometrically-invalid (OCR) rows:" % len(dropped))
        for dB, m, z, tip in dropped:
            print("  W%s x %s x %d  (tip %.3f > dB)" % (dB, m, z, tip))


if __name__ == "__main__":
    main()
